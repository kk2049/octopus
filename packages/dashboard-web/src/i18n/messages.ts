export function message(
  language: DashboardLanguageId,
  key: MessageKey,
  values: MessageValues = {},
): string {
  return interpolateMessage(MESSAGES[language][key], values);
}

export function interpolateMessage(template: string, values: MessageValues): string {
  return template.replace(/\{([^}]+)\}/g, (token, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : token,
  );
}

export function navigationLabel(language: DashboardLanguageId, id: string, fallback: string): string {
  return NAV_LABELS[language][id] ?? fallback;
}

export function themeLabel(language: DashboardLanguageId, id: string, fallback: string): string {
  if (id === "classic") return message(language, "theme.classic");
  if (id === "feishu") return message(language, "theme.feishu");
  return fallback;
}
